def mol2pdb(outdir, inp, segid, resid):
	ligXYZ = {}
	#segid = 'LIG'
	#resid = 'MOL'
	resid = int(resid)
	fp = open(f'{inp}.mol2', 'r')

	line=fp.readline()
	while line:
		if line[0:13] == '@<TRIPOS>ATOM':
			line=fp.readline()
			while line[0:13] != '@<TRIPOS>BOND':
				lns=line.split()
				ligXYZ[lns[1]]=lns[2:5]
				#print(ligXYZ)
				line=fp.readline()
			break
		else:
			line=fp.readline()
	fp.close()

	fp=open(f'{outdir}/{inp}.pdb','w')
	row = 0
	for at in ligXYZ:
		row+=1 
		fp.write("ATOM  %5d %-4s %4s%5d    %8.3f%8.3f%8.3f%6.2f%6.2f      %-4s\n" % (\
				row,at,segid,resid,float(ligXYZ[at][0]),float(ligXYZ[at][1]),float(ligXYZ[at][2]),1,0,segid))

	fp.write("TER\nEND")
	fp.close()
	
def change_rtf(outdir, inp, ext, resname):
	fp = open(f'{inp}{ext}', 'r') 
	fout = open(f'{outdir}/{inp}{ext}','w') 

	for line in fp:
		if line.startswith('RESI'):
			l = line.split()
			l[1] = str(resname)
			fout.write(' '.join(l) + '\n')
			#print(l)
		else:
			fout.write(line)

	fp.close()
	fout.close()

